/**
 * Builds src/data/images.generated.ts (width, height and a tiny blur placeholder for
 * every photo in public/images/photos). Run after adding or replacing photography:
 *   node scripts/build-image-manifest.mjs
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")));
const dir = path.join(root, "public", "images", "photos");
const out = path.join(root, "src", "data", "images.generated.ts");

const manifest = {};
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".jpg")).sort()) {
  const key = file.slice(0, -4);
  const p = path.join(dir, file);
  const meta = await sharp(p).metadata();
  const blur = await sharp(p).resize(12, 12, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  manifest[key] = { src: `/images/photos/${file}`, width: meta.width, height: meta.height, blur: `data:image/webp;base64,${blur.toString("base64")}` };
}

fs.writeFileSync(
  out,
  `// Generated by scripts/build-image-manifest.mjs — do not edit by hand.\nexport const PHOTOS = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type PhotoKey = keyof typeof PHOTOS;\n`,
);
console.log(`Wrote ${Object.keys(manifest).length} images to ${path.relative(root, out)}`);
